import { pageHead } from "#/lib/seo";
import { toolByHref } from "#/lib/tools";

const TOOL = toolByHref("/multi-pdf-chat");

const TITLE = "Chat With Multiple PDFs at Once — Multi-Document AI";
const DESCRIPTION =
  "Ask one question across up to 5 PDFs. Answers name the document and page they came from.";

export const Route = createFileRoute("/multi-pdf-chat")({
  head: () => pageHead({ title: TITLE, description: DESCRIPTION, path: "/multi-pdf-chat" }),
  component: MultiPdfChatPage,
});

const FAQ = [
  {
    question: "What happens to my PDFs?",
    answer:
      "The text is read in your browser, then the question and that text are sent to our AI provider to produce an answer — this is the one tool here that cannot work entirely offline, because an answer has to be generated by a model somewhere. The provider receives the extracted text of the documents you added, for the request you made. We do not keep your files or your questions, and our AI endpoint discards what it receives once it has answered. If that matters for what you are uploading, do not use this tool, or use the local-only tools instead.",
  },
  {
    question: "Why does it cite a page number sometimes and not others?",
    answer:
      "A page reference is only shown when the answer actually identified where the claim came from, or when we can match it to a page in the uploaded file. We never guess one. An answer with no page attached means the claim was found in the document but we could not pin it to a single page — which is normal when an answer draws on a passage that runs across a page break.",
  },
  {
    question: "How many PDFs can I ask about at once?",
    answer:
      "Five. That is the point where answers stop being readable side by side, and the point at which a single prompt would start dropping sources without saying so. Every file you add is named in the request, so you can see exactly what was read.",
  },
  {
    question: "What if one of my files is a scan or is password-protected?",
    answer:
      "You will be told which file failed and why, and the rest still work — a single unreadable file does not take the others down with it. For a scan, run it through the OCR tool first and add the result here. For a password-protected file, remove the password and add it again.",
  },
  {
    question: "Is the answer always right?",
    answer:
      "No. The model can misread a document, and it can be misled by text inside a PDF that is written to look like an instruction — we guard against that, but not perfectly. Read answers as a summary to check, not as a source of fact, and open the cited page before you rely on anything important.",
  },
];

interface Turn extends ChatMessage {
  citations: Citation[];
}

function MultiPdfChatPage() {
  const [chosen, setChosen] = useState<AcceptedFile[]>([]);
  const [turns, setTurns] = useState<Turn[]>([]);
  const [chatError, setChatError] = useState<string | null>(null);
  const [documents, setDocuments] = useState<ExtractedDocument[]>([]);
  const reading = useRef(false);
  const run = useToolRun(TOOL.name);

  const ready = documents.length > 0;

  function add(files: AcceptedFile[]) {
    const room = MAX_DOCUMENTS - chosen.length;
    if (room <= 0) return;
    const next = [...chosen, ...files].slice(0, MAX_DOCUMENTS);
    const dropped = chosen.length + files.length - next.length;
    if (dropped > 0) {
      run.fail(`You can ask about ${MAX_DOCUMENTS} PDFs at a time — ${dropped} file${dropped > 1 ? "s were" : " was"} left out.`);
    } else {
      run.reset();
    }
    setChosen(next);
  }

  function remove(id: string) {
    setChosen((current) => current.filter((file) => file.id !== id));
    // A removed file must not survive in the extracted set, or the chat would
    // keep answering from a document the visitor can no longer see.
    const kept = documents.filter((document) => document.id !== id);
    if (kept.length !== documents.length) {
      setDocuments(kept);
      setTurns([]);
    }
    run.reset();
  }

  function startOver() {
    setChosen([]);
    setTurns([]);
    setChatError(null);
    setDocuments([]);
    run.reset();
  }

  const readDocuments = useCallback(async () => {
    // `run` carries the progress and cancel plumbing but its `results` slot is
    // for downloadable files, which this tool has none of — so the extracted
    // documents live in their own state and the run ends with nothing stored.
    await run.run(async (report) => {
      // Sequential rather than parallel: pdf.js keeps one worker, and running
      // five extractions at once on a phone stalls the tab long enough that the
      // progress bar looks frozen.
      const found: ExtractedDocument[] = [];
      const failures: string[] = [];
      for (const [index, file] of chosen.entries()) {
        const outcome = await extractDocument(
          file.id,
          file.file,
          (percent, label) => report((index + percent / 100) / chosen.length, label),
        );
        if ("document" in outcome) found.push(outcome.document);
        else failures.push(outcome.error);
      }

      if (found.length === 0) {
        throw new Error(
          failures[0] ?? "None of those PDFs could be read. Scans need OCR first.",
        );
      }
      // Not fatal, but never silent: a document that was dropped changes what
      // the answer can legitimately cover.
      if (failures.length > 0) setChatError(failures.join(" "));
      setDocuments(found);
      return [];
    });
  }, [chosen, run]);

  const ask = useCallback(
    async (question: string) => {
      if (documents.length === 0 || reading.current) return;
      reading.current = true;
      setChatError(null);
      const history = turns.map((turn) => ({ role: turn.role, content: turn.content }));
      setTurns((current) => [
        ...current,
        { role: "user", content: question, timestamp: Date.now(), citations: [] },
      ]);

      try {
        const { answer, citations } = await askAcrossDocuments(documents, question, history);
        setTurns((current) => [
          ...current,
          { role: "assistant", content: answer, timestamp: Date.now(), citations },
        ]);
      } catch (error) {
        setChatError(
          error instanceof Error
            ? error.message
            : "The AI provider did not answer. Please try again.",
        );
      } finally {
        reading.current = false;
      }
    },
    [documents, turns],
  );

  const busy = run.status === "working";
  const overLimit = chosen.length > MAX_DOCUMENTS;

  return (
    <ToolShell tool={TOOL} faq={FAQ} about={<About />}>
      <ToolPanel>
        {!ready && (
          <>
            <FileUploader
              kind="pdf"
              multiple
              toolName={TOOL.name}
              onFiles={add}
              onRejected={run.fail}
              label={`Add up to ${MAX_DOCUMENTS} PDFs`}
              hint={`Each up to ${MAX_FILE_LABEL}. Most questions need two or three files — beyond five the answers get hard to check.`}
            />
            {chosen.length > 0 && (
              <>
                <ChosenFiles
                  kind="pdf"
                  files={chosen}
                  onRemove={remove}
                  disabled={busy}
                  status={`${chosen.length} of ${MAX_DOCUMENTS} added`}
                />
                {overLimit && (
                  <p className="text-sm text-red-600 dark:text-red-400">
                    Only the first {MAX_DOCUMENTS} files were kept. Remove one to add
                    another.
                  </p>
                )}
                <ErrorMessage message={run.error ?? undefined} />
                {busy && <ProgressBar progress={run.progress} onCancel={run.cancel} />}
                <button
                  type="button"
                  onClick={readDocuments}
                  disabled={busy || chosen.length === 0}
                  className="w-full rounded-xl bg-brand-600 px-6 py-3.5 text-sm font-semibold text-white shadow-sm transition-colors hover:bg-brand-700 disabled:cursor-not-allowed disabled:opacity-50"
                >
                  {busy ? "Reading your PDFs..." : "Start asking questions"}
                </button>
              </>
            )}
          </>
        )}

        {ready && (
          <>
            <div className="flex flex-wrap items-center justify-between gap-2">
              <p className="text-sm font-semibold text-ink-700 dark:text-ink-200">
                Asking across {documents.length} document{documents.length > 1 ? "s" : ""}
              </p>
              <button
                type="button"
                onClick={startOver}
                className="text-sm text-ink-500 underline underline-offset-2 hover:text-ink-700 dark:text-ink-400 dark:hover:text-ink-200"
              >
                Change documents
              </button>
            </div>

            <ul className="flex flex-wrap gap-1.5">
              {documents.map((document) => (
                <li
                  key={document.id}
                  title={`${document.chars.toLocaleString()} characters, ${document.pages.length} page${document.pages.length === 1 ? "" : "s"} with text`}
                  className="max-w-[16rem] truncate rounded-lg bg-ink-100 px-2.5 py-1 text-xs font-medium text-ink-600 dark:bg-ink-800 dark:text-ink-300"
                >
                  {document.name}
                </li>
              ))}
            </ul>

            {run.status === "error" && <ErrorMessage message={run.error ?? undefined} />}
            {chatError && <ErrorMessage message={chatError ?? undefined} />}

            <OptionGroup
              legend="Start with one of these"
              hint="Each one asks about every document you added."
            >
              <div className="grid gap-2 sm:grid-cols-2">
                {QUICK_ACTIONS.map((action) => (
                  <button
                    key={action.id}
                    type="button"
                    onClick={() => ask(action.prompt)}
                    disabled={reading.current}
                    className="rounded-xl bg-white px-4 py-3 text-left text-sm text-ink-700 ring-1 ring-ink-200 transition-colors hover:bg-brand-50 hover:text-brand-700 hover:ring-brand-200 disabled:opacity-50 dark:bg-ink-800 dark:text-ink-200 dark:ring-ink-700 dark:hover:bg-brand-600/10 dark:hover:text-brand-300 dark:hover:ring-brand-600/30"
                  >
                    {action.label}
                  </button>
                ))}
              </div>
            </OptionGroup>

            <AiChat
              onSend={ask}
              messages={turns}
              isLoading={reading.current}
              inputPlaceholder="Ask a question across all of these documents..."
              error={null}
              renderExtras={(index) => {
                const citations = turns[index]?.citations ?? [];
                if (citations.length === 0) return null;
                return (
                  <div className="mt-2 flex max-w-full flex-wrap gap-1.5">
                    {citations.map((citation) => (
                      <span
                        key={`${citation.documentId}:${citation.page ?? "all"}`}
                        className="rounded-md bg-brand-50 px-2 py-1 text-[11px] font-medium text-brand-700 ring-1 ring-brand-100 dark:bg-brand-600/10 dark:text-brand-300 dark:ring-brand-600/30"
                      >
                        {citation.documentName}
                        {citation.page !== null ? `, p. ${citation.page}` : ""}
                      </span>
                    ))}
                  </div>
                );
              }}
            />

            <Disclosure />
          </>
        )}
      </ToolPanel>
    </ToolShell>
  );
}

/**
 * The disclosure sits at the point of use rather than in the FAQ.
 *
 * This is the only tool on the site whose document text leaves the browser, so
 * burying the fact in a FAQ page would misrepresent it to anyone who just reads
 * the tool. The retention wording below matches what the endpoint actually does:
 * nothing is written to disk, and the request is discarded once answered.
 */
function Disclosure() {
  return (
    <div
      role="note"
      className="rounded-2xl bg-brand-50 px-4 py-3.5 ring-1 ring-brand-100 dark:bg-brand-600/10 dark:ring-brand-600/30"
    >
      <p className="text-sm text-brand-900 dark:text-brand-200">
        Your PDFs are read in this browser tab. To produce an answer, the extracted
        text and your question are sent to our AI provider (Groq) for that request
        only. Your files are never stored on our servers, and the request is
        discarded once it has been answered — there is no retention window to worry
        about, because nothing is written down. The one thing to be aware of is that
        until that request completes, this page is working with your document text
        on a third-party service, so it is worth thinking twice before uploading
        anything confidential.
      </p>
    </div>
  );
}

function About() {
  return (
    <>
      <p>
        Most people do not have one document open. They have a contract and a
        schedule, a report and its appendix, three papers for next week's seminar.
        Each is readable on its own, and none of them answers the question that
        actually matters — the one that only exists <em>between</em> them. Which
        deadline binds first? Where do these two contradict each other? What does
        this new draft change?
      </p>
      <p>
        This tool holds several PDFs at once and keeps each one labelled
        throughout, so an answer can say which document it came from and, where
        that is knowable, which page. That is the difference from pasting
        everything into a single chat: once the document boundaries are gone, the
        model has no way to attribute anything and you have no way to check it.
      </p>
      <p>
        <strong>Answers are generated, not verified.</strong> A citation tells you
        which document to open — it is not a guarantee that the document says
        exactly that. And because a PDF is untrusted input, one containing text
        written to look like an instruction can still mislead the model; we
        delimit the document text and tell the model to report such attempts rather
        than follow them, but no prompt-level defence is perfect. Treat every
        answer as a summary to check against the original.
      </p>
      <p>
        The text of your documents and your questions go to a third-party AI
        provider to generate the answer. Nothing is stored, but that request does
        leave your browser — the details are stated at the top of the tool, not
        hidden here. For anything you cannot send to a third party, use the
        local-only tools on this site instead.
      </p>
    </>
  );
}