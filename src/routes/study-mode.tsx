/**
 * The order the materials appear in.
 *
 * This is the order someone actually revises in — read the summary, learn from
 * the notes, then test yourself on the questions, then keep the cards. Tabs are
 * listed in this sequence rather than alphabetically so the panel reads as a
 * route through the material rather than a set of interchangeable outputs.
 */
const TABS: { id: StudyMaterial; blurb: string }[] = [
  { id: "summary", blurb: "What this document is and what it argues." },
  { id: "notes", blurb: "The detail to revise from, grouped by topic." },
  { id: "questions", blurb: "Test yourself, with an explanation for every answer." },
  { id: "flashcards", blurb: "Quick recall for the bus or the queue." },
];

