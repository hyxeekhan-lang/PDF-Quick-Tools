function StudyModePage() {
  const [file, setFile] = useState<AcceptedFile | null>(null);
  const [tab, setTab] = useState<StudyMaterial>("summary");
  const [count, setCount] = useState<StudyCount>(10);
  const [difficulty, setDifficulty] = useState<StudyDifficulty>("Medium");

  const [summary, setSummary] = useState<StudySummary | null>(null);
  const [notes, setNotes] = useState<StudyNotes | null>(null);
  const [questions, setQuestions] = useState<StudyQuestion[] | null>(null);
  const [cards, setCards] = useState<Flashcard[] | null>(null);
  const [copied, setCopied] = useState(false);

  const run = useToolRun(tool.name);
  const busy = run.status === "working";

  function add(incoming: AcceptedFile[]) {
    setFile(incoming[0] ?? null);
    // Every result is dropped with the file. Keeping a previous document's
    // questions on screen while a new file is loaded is how someone ends up
    // revising the wrong lecture.
    setSummary(null);
    setNotes(null);
    setQuestions(null);
    setCards(null);
    setTab("summary");
    if (run.status !== "idle") run.reset();
  }

  function startOver() {
    setFile(null);
    setSummary(null);
    setNotes(null);
    setQuestions(null);
    setCards(null);
    run.reset();
  }

  const handleCopy = useCallback(() => {
    const text = questionsToText(questions ?? []);
    navigator.clipboard
      ?.writeText(text)
      .then(() => {
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      })
      .catch(() => setCopied(false));
  }, [questions]);

  const generate = useCallback(
    (material: StudyMaterial = tab) => {
      if (!file) return;
      void run.run(async (report) => {
        report(8, "Reading your document");
        const text = await extractPdfText(file.file);
        if (!text.trim()) {
          throw new FriendlyError(
            "Could not read text from this PDF, so there is nothing to generate from. If it is a scan, run it through OCR PDF first and try again.",
          );
        }

        // Four separate requests rather than one combined one. A single prompt
        // asking for all four comes back thin across every part, and the failure
        // is invisible — each part is still *something*. Asking again for one
        // material is what makes "Generate more" mean something.
        if (material === "summary") {
          report(40, "Writing the summary");
          setSummary(await getSummary(text));
          setTab("summary");
        } else if (material === "notes") {
          report(40, "Building revision notes");
          setNotes(await getNotes(text));
          setTab("notes");
        } else if (material === "questions") {
          report(40, `Writing ${count} questions`);
          const result = await getQuestions(text, count, difficulty);
          const normalised = normalizeQuestions(result);
          if (normalised.length === 0) {
            throw new FriendlyError(
              "The AI returned a question set with nothing in it. Try again, or use a longer document — a one-paragraph PDF often does not carry enough to build questions from.",
            );
          }
          setQuestions(normalised);
          setTab("questions");
        } else {
          report(40, `Writing ${count} flashcards`);
          const result: StudyCards = await getCards(text, count);
          setCards(
            (result.cards ?? []).map((card) => ({
              question: card.question,
              answer: card.answer,
              topic: card.topic,
            })),
          );
          setTab("flashcards");
        }

        report(100, "Done");
        // This tool produces no files — the output is text the visitor reads,
        // copies or prints, so there is nothing for the run to hold on to.
        return [];
      });
    },
    [file, run, tab, count, difficulty],
  );

  const hasAnything = summary || notes || questions || cards;
  // With a file but no material yet, the primary action is "make the thing I am
  // looking at". Everything else is a deliberate second request.
  const showPickers = !hasAnything;

  return (
    <ToolShell tool={tool} faq={FAQ} about={<About />}>
      <ToolPanel>
        {!file && (
          <FileUploader
            kind="pdf"
            toolName={tool.name}
            onFiles={add}
            onRejected={run.fail}
            label="Upload a PDF to study"
          />
        )}

        {run.status === "error" && !file && run.error && (
          <ErrorMessage message={run.error} />
        )}

        {file && (
          <div className="space-y-5">
            {/* Which document everything below came from. Without this, four
                tabs of generated text is four sets of claims with no origin. */}
            <div className="flex items-center gap-3">
              <div className="min-w-0 flex-1">
                <p className="truncate text-sm font-semibold text-ink-900 dark:text-white">
                  {file.name}
                </p>
                <p className="text-xs text-ink-500">
                  {(file.size / 1024 / 1024).toFixed(1)} MB ·{" "}
                  {hasAnything ? "one upload, four ways to revise it" : "not generated yet"}
                </p>
              </div>
              <button type="button" onClick={startOver} className={button("ghost", "sm")}>
                Change file
              </button>
            </div>

            {/* Tabs. Always visible once there is a file, because switching to a
                tab you have not generated yet is how you find out it is empty. */}
            <div
              role="tablist"
              aria-label="Study materials"
              className="grid grid-cols-2 gap-2 sm:grid-cols-4"
            >
              {TABS.map(({ id, blurb }) => {
                const ready =
                  id === "summary"
                    ? summary
                    : id === "notes"
                      ? notes
                      : id === "questions"
                        ? questions
                        : cards;
                const active = tab === id;
                return (
                  <button
                    key={id}
                    role="tab"
                    type="button"
                    aria-selected={active}
                    onClick={() => setTab(id)}
                    className={cx(
                      "rounded-xl px-3 py-2.5 text-left text-sm font-semibold ring-1 transition",
                      active
                        ? "bg-brand-600 text-white ring-brand-600"
                        : "bg-white text-ink-700 ring-ink-200 hover:bg-ink-50 dark:bg-ink-900 dark:text-ink-200 dark:ring-ink-700 dark:hover:bg-ink-800",
                    )}
                  >
                    {MATERIAL_LABELS[id]}
                    {ready ? (
                      <span
                        className={cx(
                          "ml-1.5 inline-block h-1.5 w-1.5 rounded-full align-middle",
                          active ? "bg-white" : "bg-emerald-500",
                        )}
                        aria-label="generated"
                      />
                    ) : (
                      <span className="ml-1.5 text-[11px] font-normal opacity-60">empty</span>
                    )}
                    <span className="mt-0.5 block text-[11px] font-normal opacity-75">
                      {blurb}
                    </span>
                  </button>
                );
              })}
            </div>

            {showPickers && (
              <div className="grid gap-5 sm:grid-cols-2">
                <OptionGroup
                  legend="How many questions and cards?"
                  hint="Applies to whichever you generate next."
                >
                  <div className="flex flex-wrap gap-2">
                    {STUDY_COUNT_OPTIONS.map((option) => (
                      <button
                        key={option}
                        type="button"
                        aria-pressed={count === option}
                        onClick={() => setCount(option)}
                        className={cx(
                          "rounded-lg px-3.5 py-2 text-sm font-semibold ring-1 transition",
                          count === option
                            ? "bg-brand-600 text-white ring-brand-600"
                            : "bg-white text-ink-700 ring-ink-200 hover:bg-ink-50 dark:bg-ink-900 dark:text-ink-200 dark:ring-ink-700 dark:hover:bg-ink-800",
                        )}
                      >
                        {option}
                      </button>
                    ))}
                  </div>
                </OptionGroup>

                <OptionGroup legend="How hard?" hint="Used for practice questions only.">
                  <div className="flex flex-wrap gap-2">
                    {STUDY_DIFFICULTIES.map((option) => (
                      <button
                        key={option}
                        type="button"
                        aria-pressed={difficulty === option}
                        onClick={() => setDifficulty(option)}
                        className={cx(
                          "rounded-lg px-3.5 py-2 text-sm font-semibold ring-1 transition",
                          difficulty === option
                            ? "bg-brand-600 text-white ring-brand-600"
                            : "bg-white text-ink-700 ring-ink-200 hover:bg-ink-50 dark:bg-ink-900 dark:text-ink-200 dark:ring-ink-700 dark:hover:bg-ink-800",
                        )}
                      >
                        {option}
                      </button>
                    ))}
                  </div>
                </OptionGroup>
              </div>
            )}

            {busy && <ProgressBar progress={run.progress} onCancel={run.cancel} />}

            {run.status === "error" && run.error && (
              <ErrorMessage
                message={run.error}
                onRetry={() => generate()}
                onStartOver={startOver}
              />
            )}

            {!busy && run.status !== "error" && !hasAnything && (
              <GenerateButton onClick={() => generate()}>
                Make my {MATERIAL_LABELS[tab].toLowerCase()}
              </GenerateButton>
            )}

            {/* The empty state for a tab the visitor has not generated yet. It
                says so plainly rather than showing a blank panel — an empty box
                next to three filled ones reads as a bug. */}
            {tab === "summary" && (
              <Material
                ready={Boolean(summary)}
                onGenerate={() => generate("summary")}
                busy={busy}
                label="summary"
              >
                {summary && <SummaryView summary={summary} />}
              </Material>
            )}

            {tab === "notes" && (
              <Material
                ready={Boolean(notes)}
                onGenerate={() => generate("notes")}
                busy={busy}
                label="revision notes"
              >
                {notes && (
                  <AiNotesPanel
                    result={notes}
                    onRegenerate={() => generate("notes")}
                    onCopy={() => {
                      const text = notesToText(notes);
                      navigator.clipboard
                        ?.writeText(text)
                        .then(() => {
                          setCopied(true);
                          setTimeout(() => setCopied(false), 2000);
                        })
                        .catch(() => setCopied(false));
                    }}
                    copied={copied}
                  />
                )}
              </Material>
            )}

            {tab === "questions" && (
              <Material
                ready={Boolean(questions)}
                onGenerate={() => generate("questions")}
                busy={busy}
                label="practice questions"
              >
                {questions && (
                  <div className="space-y-4">
                    <div className="flex flex-wrap items-center gap-2">
                      <button type="button" onClick={handleCopy} className={button("secondary", "sm")}>
                        {copied ? "Copied" : "Copy questions"}
                      </button>
                      <p className="text-xs text-ink-500">
                        {count} questions · {difficulty}
                      </p>
                    </div>
                    <AiQuizPanel
                      questions={questions}
                      onRegenerate={() => generate("questions")}
                    />
                  </div>
                )}
              </Material>
            )}

            {tab === "flashcards" && (
              <Material
                ready={Boolean(cards)}
                onGenerate={() => generate("flashcards")}
                busy={busy}
                label="flashcards"
              >
                {cards && (
                  <AiFlashcardPanel
                    cards={cards}
                    onRegenerate={() => generate("flashcards")}
                  />
                )}
              </Material>
            )}

            {hasAnything && (
              <AiNotice className="mt-2">
                Generated from {file.name} by an AI model. It can be wrong, and it
                works from the text it could read — not from your understanding of
                the subject. Check anything you intend to revise from. If a question
                or a card here is clearly not in your document, please report it:
                that is a real failure, not a rounding error.
              </AiNotice>
            )}
          </div>
        )}
      </ToolPanel>
    </ToolShell>
  );
}

/**
 * A tab's frame: either its content, or an honest statement that nothing has
 * been generated for it yet plus the one button that does that.
 */
function Material({
  ready,
  busy,
  label,
  onGenerate,
  children,
}: {
  ready: boolean;
  busy: boolean;
  label: string;
  onGenerate: () => void;
  children: React.ReactNode;
}) {
  if (ready) return <>{children}</>;
  if (busy) return null;
  return (
    <div className="rounded-2xl bg-ink-50 p-5 text-center dark:bg-ink-800/50">
      <p className="text-sm text-ink-600 dark:text-ink-300">
        No {label} yet for this document.
      </p>
      <button type="button" onClick={onGenerate} className={button("secondary", "sm", "mt-3")}>
        Generate {label}
      </button>
    </div>
  );
}

function SummaryView({ summary }: { summary: StudySummary }) {
  return (
    <div className="animate-blur-in space-y-5">
      <p className="leading-relaxed text-ink-700 dark:text-ink-200">{summary.summary}</p>

      {summary.keyPoints.length > 0 && (
        <div>
          <h3 className="text-sm font-semibold text-ink-900 dark:text-white">Key points</h3>
          <ul className="mt-2 space-y-1.5">
            {summary.keyPoints.map((point, index) => (
              <li key={index} className="flex gap-2 text-sm text-ink-700 dark:text-ink-200">
                <span aria-hidden="true" className="text-brand-600 dark:text-brand-400">·</span>
                {point}
              </li>
            ))}
          </ul>
        </div>
      )}

      {summary.topics.length > 0 && (
        <div>
          <h3 className="text-sm font-semibold text-ink-900 dark:text-white">Topics covered</h3>
          <div className="mt-2 flex flex-wrap gap-1.5">
            {summary.topics.map((topic, index) => (
              <span
                key={index}
                className="rounded-full bg-ink-100 px-2.5 py-1 text-xs font-medium text-ink-700 dark:bg-ink-800 dark:text-ink-200"
              >
                {topic}
              </span>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}

/** Plain text of a question set, for pasting into a document or a revision app. */
function questionsToText(questions: StudyQuestion[]): string {
  return questions
    .map((question, index) => {
      const lines = [`${index + 1}. ${question.question}`];
      question.options?.forEach((option, optionIndex) => {
        lines.push(`   ${String.fromCharCode(65 + optionIndex)}) ${option}`);
      });
      lines.push(`   Answer: ${question.correct}`);
      if (question.explanation) lines.push(`   Why: ${question.explanation}`);
      return lines.join("\n");
    })
    .join("\n\n");
}

function notesToText(notes: StudyNotes): string {
  const lines = [notes.title, "", notes.overview];
  for (const section of notes.sections) {
    lines.push("", section.heading);
    for (const point of section.points) lines.push(`• ${point}`);
    if (section.details) lines.push("", section.details);
  }
  if (notes.summary) lines.push("", notes.summary);
  return lines.join("\n");
}

function About() {
  return (
    <div className="space-y-3">
      <p>
        Upload one PDF and get a summary, revision notes, practice questions and
        flashcards — four things a lecture, chapter or paper usually needs, without
        uploading it four times. Each is generated separately, so each is as long
        as it should be.
      </p>
      <p>
        Everything is generated from the document's text and nothing else. Each
        question comes with an explanation naming the part of the document it came
        from, so you can check the answer instead of trusting it — which is the
        only way to use generated study material honestly.
      </p>
    </div>
  );
}